"""Capture the real UI against the isolated synthetic demo, never production."""
import hashlib
import json
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def main():
    from playwright.sync_api import sync_playwright
    from scripts.demo import demo_app
    import socket
    import threading
    import uvicorn

    output = ROOT / "docs/images/portfolio"
    output.mkdir(parents=True, exist_ok=True)
    # Reserve the port before launching, avoiding collisions with live services.
    with socket.socket() as listener:
        listener.bind(("127.0.0.1", 0))
        port = listener.getsockname()[1]
        with demo_app(port) as app:
            server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, access_log=False, proxy_headers=False, log_level="error"))
            thread = threading.Thread(target=server.run, kwargs={"sockets": [listener]}, daemon=True)
            thread.start()
            try:
                for _ in range(100):
                    if server.started:
                        break
                    time.sleep(0.05)
                if not server.started:
                    raise RuntimeError("Synthetic server failed to start")
                manifest = {"source": "Isolated temporary demo; all imagery generated by scripts/demo.py", "screenshots": []}
                with sync_playwright() as browser_tool:
                    browser = browser_tool.chromium.launch()
                    try:
                        for name, width, height, route in [("desktop",1440,1000,"overview"),("tablet",834,1112,"overview"),("mobile",390,844,"overview"),("activity",1440,1000,"events")]:
                            context = browser.new_context(viewport={"width":width,"height":height}, device_scale_factor=1, timezone_id="UTC", locale="en-GB", service_workers="allow", reduced_motion="reduce")
                            page = context.new_page()
                            errors = []
                            page.on("pageerror", lambda error: errors.append(str(error)))
                            # Fail closed if a future UI change tries an external service.
                            context.route("**/*", lambda route: route.continue_() if route.request.url.startswith(f"http://127.0.0.1:{port}/") else route.abort())
                            page.goto(f"http://127.0.0.1:{port}/#{route}")
                            page.locator("#dashboard").wait_for(state="visible")
                            page.locator(".camera-card").first.wait_for(state="attached")
                            page.wait_for_function("() => [...document.querySelectorAll('.camera-card img')].every(i=>i.complete && i.naturalWidth>0)")
                            if route == "events":
                                page.locator("#timeline-status").filter(has_text="events across").wait_for()
                            if name == "mobile":
                                page.locator(".camera-card").first.evaluate("el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 150)")
                            if name == "activity":
                                page.locator("#timeline-overview").evaluate("el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 100)")
                            assert not errors, errors
                            assert page.evaluate("() => document.documentElement.scrollWidth <= innerWidth"), name+" has horizontal overflow"
                            file = output / (name+".png")
                            page.screenshot(path=str(file), animations="disabled")
                            manifest["screenshots"].append({"file": file.name, "width":width,"height":height,"sha256":hashlib.sha256(file.read_bytes()).hexdigest()})
                            context.close()
                    finally:
                        browser.close()
                (output / "manifest.json").write_text(json.dumps(manifest, indent=2)+"\n")
                print("Captured four synthetic previews; browser errors and horizontal overflow checks passed.")
            finally:
                server.should_exit = True
                thread.join(timeout=10)
                if thread.is_alive():
                    raise RuntimeError("Synthetic server did not stop")


if __name__ == "__main__":
    main()
